package com.reactiveplatform.inventory.domain;

import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.Version;
import org.springframework.data.relational.core.mapping.Table;

import java.time.Instant;

/**
 * Stock for one SKU (a row in MySQL, mapped by Spring Data R2DBC).
 * <p>
 * R2DBC is NOT JPA: no lazy loading, no dirty checking, no relationships, no cascade.
 * An entity is a plain row; you save exactly what you pass in.
 * <p>
 * {@link Version}: every update runs {@code ... WHERE sku = ? AND version = ?}. If another transaction
 * changed the row first, 0 rows match and Spring throws OptimisticLockingFailureException.
 * It also tells Spring Data whether a row is new: version == null -> INSERT, otherwise UPDATE
 * (needed because the id - the SKU - is assigned by us, not generated by the database).
 */
@Table("inventory_item")
public record InventoryItem(
        @Id String sku,
        int available,
        int reserved,
        @Version Long version,
        Instant updatedAt
) {

    public static InventoryItem newItem(String sku, int available) {
        return new InventoryItem(sku, available, 0, null, Instant.now());
    }

    /** Moves stock from "available" to "reserved" - used by the optimistic strategy. */
    public InventoryItem reserve(int quantity) {
        return new InventoryItem(sku, available - quantity, reserved + quantity, version, Instant.now());
    }
}
